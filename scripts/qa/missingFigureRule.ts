/**
 * 「본문이 그림을 지목하는데 그림이 없다」를 판정하는 **단 하나의 규칙**.
 *
 * 세는 쪽(`report-missing-figures.ts`)과 잠그는 쪽(`apply-missing-figure-lock.ts`)이
 * **이 파일 하나만** 읽는다. 목록을 양쪽에 각각 손으로 쓰면 둘이 **같이 눈이 먼다**
 * — 2026-08-18 `le`/`ge` 사건이 정확히 그 자리였다(CLAUDE.md).
 *
 * ## 열쇠는 「그림」이라는 낱말이 아니라 **지시어**다
 *
 * 낱말로 세면 1,499건이 걸리는데 그중 상당수가 멀쩡하다 — 「줄기와 잎 그림」은 표가 본문에
 * 글자로 들어 있고, 「그림그래프」는 낱말만 나오는 개념 문항이다. 반대로 「그래프」로 세면
 * 3,373건이 걸리는데 표본 14건이 **전부** 대수식만으로 풀리는 멀쩡한 문항이었다.
 * 그래서 본문이 지면의 그림을 **가리키는가**로 갈랐다.
 *
 * ## 왜 단계가 둘인가 — 적대적 리뷰가 잡은 것 (2026-08-18)
 *
 * 처음엔 「오탐 목록을 먼저 보고, 안 걸리면 지시어를 본다」 한 단계였다. 그러면
 * **오탐 목록이 지시어를 항상 이긴다.** 실측으로 세 가지가 깨졌다:
 *
 * 1. 「**다음 그림과 같이** … 나무의 **그림자**가 벽에 걸쳐 있다」 — 그림자 예외가 이겨서
 *    그림 없이 출제 가능 상태로 살아 있었다(`019fd1db-9c8f`). 그림이 붙어 있는 행 7,879건에
 *    같은 규칙을 대 보니 **22건이 「불필요」로 나왔다** — 그림이 있는데 필요 없다는 뜻이니
 *    그 자체가 반증이다(그림자 15 · 줄기와잎 4 · 그림으로나타내 3).
 * 2. 「**다음 상자그림에서** 중앙값을 구하시오」 — `상자그림에서` 예외가 이겼다.
 *    「진짜 상자그림 문항은 지시어를 함께 쓴다」던 내 주석이 바로 그 경우를 삼켰다.
 * 3. 「**다음 그림 3개** 중 옳은 것은?」 — `그림 N개` 예외가 이겼다.
 *
 * 그래서 **강한 지시어**(방향어 + 그림류 / 「그림과 같」 / `<그림 1>`)는 예외를 이기고,
 * **약한 지시어**(`그림에서`·`그림이다` 처럼 문맥에 따라 갈리는 것)만 예외에 진다.
 *
 * ## 「줄기와 잎 그림」은 낱말로 못 가른다 — 표가 실제로 있는지 본다
 *
 * 표가 글자로 들어 있으면 그림이 없어도 풀린다. 그런데 같은 문구로 시작하고 **표가 없는**
 * 문항이 8건 있었고 여럿이 출제 가능 상태였다(「…줄기와 잎 그림이다. 기록이 20회 미만인
 * 학생 수를 구하시오.」 — 자료가 어디에도 없다). 그래서 문구가 아니라 표의 실재를 본다.
 */

/**
 * **강한 지시어** — 예외 목록보다 우선한다. 지면의 그림을 콕 집어 가리킨다.
 *
 * · 방향어 뒤에 그림류가 오는 형태(`다음 그림`, `오른쪽 상자그림`, `다음 전개도`).
 *   사이에 짧은 수식어를 허용해 「다음 **상자**그림」·「아래 **줄기와 잎** 그림」을 잡는다.
 * · `그림그래프`·`그림자` 는 뒤보기로 뺀다 — 「다음 그림그래프에서」가 강한 지시어가 되면
 *   개념 문항이 유실로 잡힌다. (「다음 그림과 같이 … 그림자」는 `그림과 같` 이 잡는다.)
 */
export const STRONG_DEICTIC =
  /(다음|위|아래|오른쪽|왼쪽)\s*(?:\S{1,6}\s*){0,2}(그림(?!그래프|자)|전개도|산점도)|그림과\s*같|[<[]\s*그림\s*\$?\d|전개도를\s*접|그림에\s*대한/;

/**
 * **약한 지시어** — 그림을 가리키는 말이지만 문맥에 따라 아닐 수 있다.
 * 예외 목록에 걸리면 진다.
 */
export const WEAK_DEICTIC =
  /그림에서|그림은|그림의|그림을\s*보|그림\s*\(가\)|그림이다|그림입니다|상자그림이\s*나타내|산점도이다|산점도는|산점도에\s*대한|산점도가/;

/**
 * 지시어처럼 보이지만 그림이 필요 없는 것 — **전부 표본을 눈으로 확인했다.**
 * · 그림그래프     : 낱말만 나오는 개념 문항
 * · 그림 카드/개   : 조작 교구를 말로 설명하는 문항
 * · 그림으로 나타내**시오** : **학생이 그린다.** 지면에 그림이 없어야 정상이다.
 *   「나타내**려고 한다**」·「나타낸」은 지면에 그림이 있는 쪽이라 넣지 않는다 —
 *   방향을 구분한다고 주석만 달고 실제로는 구분하지 못하던 자리다(적대적 리뷰 지적).
 * · 펼쳐 놓은 그림  : 전개도의 «이름»을 묻는 말뿐인 문항
 * · 상자그림에서    : 개념을 가리킨다. 「**다음** 상자그림에서」는 강한 지시어가 이긴다.
 * · ~~그림자~~     : **뺐다.** 「가로등 그림자」 문항은 수치만으로 풀리는 것도 있지만
 *   그림이 붙어 있는 것이 15건이었다 — 낱말로는 못 가른다. 예외로 두면 「불필요」라고
 *   단정하게 되므로, 강한 지시어가 없으면 **`미분류` 로 남겨 사람이 보게** 한다.
 *   `미분류` 는 잠그지 않으므로 멀쩡한 문항이 조용히 빠지지 않는다.
 */
export const NOT_A_FIGURE =
  /그림그래프|그림\s*카드|그림\s*하나|그림\s*\d+\s*개|그림을\s*그린|그림으로\s*나타내(시오|어라|보|자)|펼쳐\s*놓은\s*그림|그림이\s*나오는|상자그림에서/;

/**
 * `[그림]` 은 **유실이 아니라 오염 자국**이다 — 추출기가 학원 로고·머리말 이미지 자리에
 * 남긴 표시다. 실제로 그 뒤에 「…기말고사칠성고 1학년 수학학원 로고…」가 딸려 온다.
 * 그림 유실과 성격이 다르므로 따로 센다(같이 세면 둘 다 안 보인다).
 */
export const CONTAMINATION = "[그림]";

export type FigureVerdict = "유실" | "오염" | "불필요" | "미분류";

/** DB 질의 조건 — 그림이 **하나도** 없는 행. */
export const NO_FIGURE_WHERE = {
  figureUrls: { isEmpty: true },
  figureSvg: null,
} as const;

/**
 * 그림을 부를 만한 낱말이 하나라도 든 행을 끌어오는 조건. 판정은 DB 가 아니라 아래 함수가 한다.
 *
 * ⚠️ 처음엔 「그림」 하나였다. 그러면 **「전개도를 접어서 만든 정육면체」처럼 「그림」이라는
 * 낱말을 안 쓰는 문항을 구조적으로 못 본다** — 실측으로 살아 있는 것이 전개도 15 · 산점도 20.
 * 질의 열쇠가 좁으면 `미분류` 발견기도 그 밖을 못 본다(적대적 리뷰 지적).
 */
export const MENTIONS_FIGURE_WHERE = {
  // `as const` 를 쓰면 Prisma 의 `OR: ProblemWhereInput[]`(가변 배열)과 안 맞는다.
  OR: [
    { content: { contains: "그림" } },
    { content: { contains: "전개도" } },
    { content: { contains: "산점도" } },
  ],
};

/**
 * 줄기와 잎 «표»가 본문에 글자로 들어 있나. 문구(`줄기와 잎 그림`)를 지운 뒤에도
 * `줄기` 와 `잎` 이 남아 있으면 표가 실린 것이다 — 표 머리가 그 두 낱말이다.
 */
export function hasStemLeafTable(content: string): boolean {
  const rest = content.replace(/줄기와\s*잎\s*그림/g, " ");
  // 표 머리가 「줄기 잎」 이다. 낱말이 따로 흩어져 있는 것으로는 표가 있다고 볼 수 없다 —
  // 「① **잎**이 가장 많은 **줄기**는」 같은 선택지에 속아 표가 그림으로만 있는 행을
  // 「불필요」로 놓쳤다(실측 `019fd1d8-cd51`).
  return /줄기\s*잎/.test(rest);
}

/**
 * 그림이 없는 행 하나를 판정한다. **`NO_FIGURE_WHERE` 로 거른 행에만 쓴다** —
 * 그림이 붙어 있는 행에 대고 물으면 답이 뜻을 잃는다.
 *
 * 순서가 규칙의 일부다: 강한 지시어 → 예외 → 줄기와 잎 → 약한 지시어 → 오염 자국 → 미분류.
 */
export function classifyFigureNeed(content: string): FigureVerdict {
  const c = content.replace(/\s+/g, " ");
  if (STRONG_DEICTIC.test(c)) return "유실";
  if (NOT_A_FIGURE.test(c)) return "불필요";
  if (/줄기와\s*잎\s*그림/.test(c)) {
    return hasStemLeafTable(c) ? "불필요" : "유실";
  }
  if (WEAK_DEICTIC.test(c)) return "유실";
  if (c.includes(CONTAMINATION)) return "오염";
  return "미분류";
}
