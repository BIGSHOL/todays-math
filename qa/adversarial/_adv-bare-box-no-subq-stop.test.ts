/**
 * 적대적 재현 🔴 — **회귀 ① 의 수리가 새 상자 경로에는 안 걸려 있다.**
 *
 * ── 무엇이 틀렸나 ──────────────────────────────────────────────────────────
 * 2026-08-18 회귀 ① («상자가 문제 속 문제까지 삼켰다») 의 수리는
 * `boxBlock.findBoxStop` 이다 — 하위 문항 번호에서 상자를 끊는다.
 * 그런데 `findBoxStop` 을 부르는 곳은 **`findBoxFrom`(마커 있는 상자) 하나뿐**이다.
 * 같은 날 새로 만든
 *   · `findBareConditionBox` — 마커 없는 «다음 조건» 상자 (+52문항)
 *   · `findEnumerationBox`   — 발문 뒤 나열 대상 상자 (+14문항)
 * 은 그 함수를 **한 번도 부르지 않는다.** 그래서 새 경로로 만든 상자는
 * 하위 문항·시험지 머리말을 그대로 삼킨다 — 고쳤다던 결함이 옆문으로 돌아왔다.
 *
 * 또 하나. 마커 있는 경로도 완전하지 않다. `findBoxStop` 은 「첫 번호가 내용 **머리**에서
 * 시작하면 하나도 끊지 않는다」고 정했다(실측 2aa85246 «상자 자기 항목 번호»).
 * 그런데 첫 항목이 하위 문항을 **가리키기만** 해도(`∘⑴의 풀이 과정에 …`) 이 면제가
 * 켜져서 **뒤에 오는 진짜 ⑴⑵ 를 통째로 삼킨다**(실측 2fd487f4).
 * 「머리에서 시작하면 전부 면제」는 전부-아니면-전무라 손상된 쪽에 유리하게 기운다.
 *
 * ── 실데이터 근거 (전수 47,152건) ──────────────────────────────────────────
 *   `npx tsx qa/adversarial/scripts/dump-suspect-boxes.ts 하위문항원`
 *     상자 안에 괄호원문자 하위 문항이 있는 것 7개 — 그중 **4개가 진짜 삼킴**
 *     e7ae0c15 · 42736426 (둘 다 마커 없는 새 경로) · 2fd487f4 · 0cedea03
 *   `npx tsx qa/adversarial/scripts/scan-render-drift.ts --kind=상자-새로생김`
 *     이번에 새로 생긴 상자 67개 중 위 둘이 하위 문항을 삼켰다.
 */
import { describe, expect, it } from "vitest";

import { splitBoxSegments } from "@/lib/math/boxBlock";

const SUB_NUMBER = /[⑴-⒇]/;

function boxItems(raw: string): string[] {
  return splitBoxSegments(raw).flatMap((seg) =>
    seg.kind === "box" ? seg.items : [],
  );
}

describe("적대적 ③ 새 상자 경로에는 하위 문항 끊기가 없다", () => {
  it("실측 e7ae0c15 — 마커 없는 조건 상자가 ⑴⑵ 를 삼킨다", () => {
    const raw = [
      "조건을 만족시키는 유리수 $a$, $b$, $c$, $d$, $e$에 대해 다음 물음에 답하시오. [합 $7$점, 부분 점수 있음]",
      "∘ $a$는 $c$보다 $1$만큼 큰 수",
      "∘ $c$는 $b$보다 $7$만큼 큰 수",
      "∘ $e$는 가장 큰 수와 가장 작은 수로부터 같은 거리에 있는 수",
      "⑴ 유리수 $a$, $b$, $c$, $d$, $e$를 작은 수부터 나열하고, 그 과정을 서술하시오.",
      "⑵ $e=1$일 때, $a+b+c+d$의 값을 구하고, 그 과정을 서술하시오.",
    ].join("\n");
    expect(boxItems(raw).some((item) => SUB_NUMBER.test(item))).toBe(false);
  });

  it("마커 있는 경로는 같은 입력을 제대로 끊는다 — 대조군", () => {
    const raw = [
      "<조건>",
      "∘ $a$는 $c$보다 $1$만큼 큰 수",
      "∘ $c$는 $b$보다 $7$만큼 큰 수",
      "∘ $e$는 가장 큰 수와 가장 작은 수로부터 같은 거리에 있는 수",
      "⑴ 유리수 $a$, $b$, $c$, $d$, $e$를 작은 수부터 나열하고, 그 과정을 서술하시오.",
      "⑵ $e=1$일 때, $a+b+c+d$의 값을 구하고, 그 과정을 서술하시오.",
    ].join("\n");
    expect(boxItems(raw).some((item) => SUB_NUMBER.test(item))).toBe(false);
  });

  it("실측 2fd487f4 — 첫 항목이 ⑴ 을 «가리키기만» 해도 끊기가 통째로 꺼진다", () => {
    // DB 원문 그대로(발췌). 앞 `<상자>` 는 자료, 뒤 `<조건>` 이 채점 조건이다.
    const raw = [
      "이 자료의 평균이 $7$ 개이고 중앙값이 $6$ 개일 때, 다음 물음에 답하시오.",
      "",
      "<상자> a, b, 8, 3, 14, 11, 2",
      "",
      "<조건>∘⑴의 풀이 과정에 평균을 구하는 식을 포함할 것." +
        "∘⑵의 풀이 과정에 각 변량의 편차를 표현할 것.⑴",
      "",
      "$a$",
      "",
      ",",
      "",
      "$b$",
      "",
      "의 값을 각각 구하시오. ⑵ 위 변량의 분산과 표준편차를 각각 구하시오.",
    ].join("\n");
    const items = boxItems(raw);
    // 조건 상자는 «채점 조건 둘» 만 담아야 한다. 지금은 진짜 ⑴⑵ 발문까지 삼킨다.
    expect(items.some((item) => /값을 각각 구하시오/.test(item))).toBe(false);
  });
});
