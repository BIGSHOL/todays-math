/**
 * 시험지 출처 — **학교 기출**인가, **학원이 만든 대비 자료**인가.
 *
 * ## 왜 가르나 (2026-08-16 적대적 리뷰에서 드러남)
 *
 * 코퍼스에 원장님이 직접 만드신 '내신 대비' 자료 144편이 학교 기출과 **구분 없이 같은
 * 무게로** 섞여 있었다. 원본 PDF 표지에 학원 로고와 "○○고 25년 2학기 중간고사 대비"가
 * 찍혀 있고, 144편 전부 정답·해설이 딸려 있다.
 *
 * 내용도 기출이 아니다 — 대비 문항 3,410개 중 **99.3%(3,385개)가 어떤 실제 기출과도
 * 일치하지 않는다.** 기출을 재편집한 것이 아니라 그 회차를 겨냥해 새로 만든 문항이다.
 *
 * **이 프로젝트가 자동화하려는 물건이 바로 그것이다.** 예측 문제지 생성기(T7.9)가
 * 만들려는 게 대비 자료다. 그걸 "그 학교 기출"로 학습하면 엔진이 **원장님의 과거 추측을
 * 학교의 출제 패턴으로 배운다** — 자기가 낸 답을 정답지로 삼는 되먹임이다.
 *
 * 실측된 피해:
 *   - 다음 회차 예상 문항 수가 평균 **+1.2문**, 최대 +3.1문 부풀려진다
 *     (대비는 25문 템플릿, 실제 기출은 21.2±2.0문)
 *   - 달서고·비슬고·영남고·영신고 고1은 **실제 기출 0편** — 그 학교 "패턴"이 전부 추측이다
 *   - 신뢰 가드(D-45)가 오히려 대비를 선호한다. 템플릿이라 81%가 정확히 100.00점이다
 *
 * ## 지우지 않는다 — 쓰는 자리가 다를 뿐이다
 *
 *   - ❌ **학교 출제 패턴 학습**(청사진 예측) — 여기서만 뺀다
 *   - ⭕ 시험 범위 판단 · 사람이 붙인 소단원/난이도 라벨
 *   - ⭕ 예측 문제지 생성기의 **대조군** — "원장님이 손으로 만드시던 것 vs 엔진이 만든 것"
 *
 * ## ⚠️ 판정의 한계 — 넓혀 읽지 말 것
 *
 * 파일 경로의 `대비` 문자열로만 가른다. 그래서 다음 둘을 못 잡는다.
 *   - 이름에 `대비`가 없는 학원 제작물 (더 있을 수 있다)
 *   - `대비`가 들어갔지만 실제 기출인 파일 (표지를 확인한 것은 4편뿐이다)
 *
 * 더 확실한 신호는 PDF 표지의 "학원 로고"인데, 추출 산출물(JSON)에는 표지 텍스트가
 * 남지 않아 적재 시점에는 쓸 수 없다. 표지 기반 분류기가 생기면 이 함수를 갈아끼운다.
 * 그때까지는 **경로가 없으면 `미상`** 으로 두고, 학습에는 **기출로 확인된 것만** 쓴다.
 */

/** 판정 근거를 사람이 되짚을 수 있게 남기는 문자열. 보고서·로그에 함께 찍는다. */
export const PAPER_SOURCE_HINT =
  "파일 경로에 '대비'가 있으면 학원 대비 자료로 본다(2026-08-16 실측 144편).";

export type PaperSource = "기출" | "대비" | "미상";

/**
 * 경로 하나로 출처를 정한다.
 *
 * 🔴 경로를 모르면 **`기출`로 단정하지 않는다.** 단정하면 대비 자료가 조용히 섞인다 —
 *    지금 고치고 있는 사고가 정확히 그것이다.
 */
export function classifyPaperSource(
  sourceFile: string | null | undefined,
): PaperSource {
  if (!sourceFile || !sourceFile.trim()) return "미상";
  return sourceFile.includes("대비") ? "대비" : "기출";
}

/**
 * 학교 출제 패턴 학습에 써도 되는가.
 *
 * **`기출`로 확인된 것만 참이다.** `미상`은 넣지 않는다 — 근거 없이 넣는 쪽이
 * 근거 없이 빼는 쪽보다 나쁘다(빠지면 "예측 불가"로 드러나지만, 섞이면 조용히 틀린다).
 */
export function isSchoolExam(sourceFile: string | null | undefined): boolean {
  return classifyPaperSource(sourceFile) === "기출";
}
