/**
 * **한 행에 문항이 여럿 뭉쳤나** — 판정 규칙 한 곳.
 *
 * 세는 쪽(`scripts/qa/report-merged-problems.ts`)과 앞으로 고치는 쪽이 같은 파일을
 * 읽는다. 목록을 양쪽에 각각 쓰면 둘이 같이 눈이 먼다(CLAUDE.md 2026-08-18).
 */

/**
 * 시험지 **머리표**. `[서술형 3]` · `[단답형 1]` · `[서술형 3~5]` · `[서술형 2-3]` 꼴이다.
 *
 * ⚠️ 여기 **범위 구분자(`~∼-`)를 넣지 않는다.** 번호만 읽으면 `[서술형 2-3]` 도
 * `[서술형 2~3]` 도 「서술형2」 하나로 접히기 때문이다. 실데이터로 재 보니 범위
 * 구분자를 넣든 빼든 **12건으로 같고 갈리는 행이 0**이라, 넣으면 시험할 수 없는
 * 장식이 된다(CLAUDE.md 2026-08-18 «가드는 망가뜨려 봐야 가드인 줄 안다»).
 *
 * ⚠️ 그리고 `-` 를 「본문 안 상호참조」로 보아 그 머리표를 **버리면 안 된다.**
 * 처음에 그렇게 했더니 하이픈으로 쓴 **범위**가 같이 죽어 진짜 뭉친 행 `3568-18`
 * (`[서술형 1]` + `[서술형 2-3]`)이 감춰졌다 — 예외가 혼자 걸러 낸 행은 그 하나뿐이었고
 * 그 하나가 오판이었다(11 → **12건**). 상호참조(`[서술형 3-⑴]의 결과를 …`)는 예외
 * 없이도 걸러진다 — **자기를 가리키는 참조는 번호가 자기와 같아서** 아래 `Set` 이 흡수한다.
 */
const HEAD = /\[\s*(서술형|논술형|단답형)\s*\$?(\d+)\$?/g;

/**
 * 이 본문이 담은 **서로 다른** 문항 머리표를 나온 순서대로 돌려준다.
 *
 * 길이가 2 이상이면 한 칸에 문항이 여럿이라는 뜻이고, 학생은 한 자리에서 두 문항을
 * 보게 된다. 「정답이 보기 중 하나인가」로는 이 부류를 **구조적으로 못 본다** —
 * 뭉친 것이 서술형이면 비객관식이라 판정 대상이 아니고, 객관식이어도 **첫 문항의
 * 보기·정답은 정확히 맞기** 때문이다(`4103-15` 는 정답 `③` 이 보기 중 하나다).
 */
export function countProblemHeads(content: string): string[] {
  const seen = new Set<string>();
  for (const m of content.matchAll(HEAD)) seen.add(`${m[1]}${m[2]}`);
  return [...seen];
}
