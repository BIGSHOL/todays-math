/**
 * **학생이 그리는 것**은 지면에 없어야 정상이다.
 * `NOT_A_FIGURE` 의 「그림으로 나타내시오」와 같은 부류인데, 실측에서 두 꼴이 더 나왔다 —
 * 「**그림으로 나타내는 과정**을 포함하여 서술하시오」(`3291-19`),
 * 「산점도를 **그리고** … 서술하시오」(`4013-17`).
 */
export const STUDENT_DRAWS =
  /(그림|산점도|그래프|도표)(으?로)?\s*나타내는\s*과정|(산점도|그래프|그림)를?\s*그리고|(산점도|그래프|그림)을\s*그려/;

/**
 * **그림 위에 «적힌» 것을 가리키면 그림이 있어야 한다.**
 * 「정육면체 전개도에서 마주 보는 면에 **적힌 두 수**」(`5239-21`) — 그 수가 어디에도
 * 없으면 못 푼다. 같은 「전개도에서」라도 `SOLID_PROPERTY` 쪽은 성질을 묻고
 * 이쪽은 **지면의 표시**를 묻는다. 그래서 이 검사를 먼저 본다.
 */
export const MARKED_ON_FIGURE =
  /(전개도|산점도|그림|그래프)[^.?!]{0,40}?(적힌|쓰인|쓰여진|표시된|나타낸\s*수)/;

/**
 * **선택지가 그림 자국만 남은 것.** 「다음 중 … 산점도로 알맞은 것은? ① $y$ ② $y$ $x$ $x$ …」
 * (`019fd1de-f6be`) 처럼 원문자 뒤에 축 이름 한두 자만 남으면, 선택지 그림이 통째로
 * 유실된 것이다. 이 문항은 **지금 출제 가능 상태**였다.
 *
 * 열쇠는 「짧다」가 아니라 **「한글이 하나도 없다」**다 — 「① 1가지」도 짧지만 한글이 있다.
 */
export function choicesAreFigureStubs(content: string): boolean {
  const parts = content.split(/[①②③④⑤]/);
  if (parts.length < 4) return false; // 원문자 선택지가 3개 미만이면 볼 것이 없다
  // `$`(수식 구분자)·백슬래시·공백을 지우고 남는 알맹이를 본다.
  const bodies = parts.slice(1).map((s) => s.replace(/[$\\]|\s/g, ""));
  // ⚠️ 「짧고 한글이 없다」로만 보면 **숫자 선택지**를 통째로 삼킨다 — 그림이 붙어 있는
  //    행에 대 보니 「① $1$ ② $2$ … ⑤ $5$」 류가 걸렸다(실측 8건). 숫자는 그 자체로
  //    멀쩡한 선택지다. 남는 것은 **빈 칸이거나 축 이름(라틴 글자)** 뿐인 경우다.
  return bodies.every((b) => /^[A-Za-z]{0,3}$/.test(b));
}

/**
 * `미분류` 로 남은 행 하나를 다시 가른다. **`미분류` 가 아닌 행에는 쓰지 마라** —
 * 답이 뜻을 잃는다(`classifyFigureNeed` 의 주석과 같은 이유).
 */
export function refineUnclassified(content: string): FigureVerdict {
  const c = content.replace(/\s+/g, " ");
  // 지면의 표시를 가리키는 쪽이 먼저다 — 「전개도에서 …적힌 두 수」는 성질 문항이 아니다.
  if (MARKED_ON_FIGURE.test(c)) return "유실";
  if (choicesAreFigureStubs(c)) return "유실";
  if (STUDENT_DRAWS.test(c)) return "불필요";
  if (SOLID_PROPERTY.test(c) && ASKS_PROPERTY.test(c)) return "불필요";
  return "미분류";
}

/**
 * 세는 쪽·잠그는 쪽이 함께 쓰는 **최종 판정**.
 * `classifyFigureNeed` 로 가르고, `미분류` 만 `refineUnclassified` 로 한 번 더 본다.
 */
export function classifyFigure(content: string): FigureVerdict {
  const v = classifyFigureNeed(content);
  return v === "미분류" ? refineUnclassified(content) : v;
}
