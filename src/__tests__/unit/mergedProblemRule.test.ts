/**
 * 🔴 한 행에 문항이 **여럿** 뭉친 것을 가려낸다.
 *
 * 픽스처는 **실제 행**이다(지어낸 문장이면 가드가 무엇을 지키는지 알 수 없다 —
 * CLAUDE.md 2026-08-19). 11건 전량을 눈으로 확인했고, 여기 넣은 것은 그중
 * **경계를 가르는** 넷과 반대쪽 둘이다.
 */
import { describe, expect, it } from "vitest";

import { countProblemHeads } from "../../lib/problem/mergedProblemRule";

describe("한 행에 문항이 여럿 뭉쳤나", () => {
  it("서로 다른 머리표가 둘이면 뭉친 것이다 — 4012-15", () => {
    const content =
      "[서술형 $2$] $A=x^{2}+4x+4$, $B=2x^{2}+3x-2$일 때, 세 다항식의 공통인수를 " +
      "찾고, $A+B-C$를 인수분해하시오. [서술형 $3$ ∼ $5$] $x=1+\\sqrt{2}$일 때, 물음에 답하시오.";
    expect(countProblemHeads(content)).toEqual(["서술형2", "서술형3"]);
  });

  /**
   * 오탐 부류 ㉠ — 한 문항이 **자기를 가리킨다.** 예외 없이도 걸러진다:
   * 자기 참조는 번호가 자기와 같으므로 `Set` 이 흡수한다.
   */
  it("본문 안 상호참조는 **두 번째 문항이 아니다** — 3078-17", () => {
    const content =
      "[서술형 $3$ ] 그림과 같이 채워진 물의 높이가 $x$ cm일 때 … 다음 물음에 답하시오. " +
      "⑴ … 상수 $a$ 의 값을 구하고, 그 과정을 서술하시오. " +
      "⑵ … 상수 $b$ 의 값을 구하고, 그 과정을 서술하시오." +
      "( [그림] 단, [서술형 $3$ -⑴]의 결과를 이용할 수 있음.)";
    expect(countProblemHeads(content)).toEqual(["서술형3"]);
  });

  /**
   * 갈래가 섞여도 센다. 이 행은 **객관식**이라 정답 `③` 이 보기 중 하나로 정확히
   * 맞는다 — 정답 대조 지표에는 「정상」으로 보인다.
   */
  it("객관식 + 단답형 + 서술형이 뭉친 것도 잡는다 — 4103-15", () => {
    const content =
      "그림은 $y=\\frac{1}{2}x^{2}-2x$ 의 그래프이다. … 부피는? [그림] " +
      "1. $\\frac{4}{3}π$ 2. $\\frac{8}{3}π$ 3. $\\frac{16}{3}π$ " +
      "[단답형 $1$ ] 그림과 같이 각 단계마다 바둑돌의 개수를 … 단계를 구하시오. [ $5$ 점] " +
      "[서술형 $2$ ] 그림과 같이 한 변의 길이가 $4$ cm인 정오각형에서 …";
    expect(countProblemHeads(content)).toEqual(["단답형1", "서술형2"]);
  });

  /**
   * 🔴 **거꾸로 걸렸던 자리.** `-` 를 「상호참조 표시」로 보고 그 머리표를 버렸더니,
   * 하이픈으로 쓴 **범위**가 같이 죽어 진짜 뭉친 행이 감춰졌다. 실데이터에서 그
   * 예외가 혼자 걸러 낸 행은 이것 하나뿐이었고, 그 하나가 오판이었다(11 → 12건).
   */
  it("`[서술형 2-3]` 은 하이픈으로 쓴 **범위**다 — 3568-18", () => {
    const content =
      "[서술형 $1$ ] $x$ 와 $y$ 가 정비례하고 … 식으로 나타내고 풀이과정을 서술하시오. " +
      "[서술형 $2-3$ ] $1909$ 년 국제 안과학회에서는 그림과 같이 … 물음에 답하시오. [그림]";
    expect(countProblemHeads(content)).toEqual(["서술형1", "서술형2"]);
  });

  it("머리표가 여덟이면 여덟을 돌려준다 — 5329-13", () => {
    const content = Array.from(
      { length: 8 },
      (_, i) => `[서술형 $${i + 1}$ ] 문항 ${i + 1} 의 발문이다.`,
    ).join(" ");
    expect(countProblemHeads(content)).toHaveLength(8);
  });

  it("머리표가 하나면 뭉친 것이 아니다", () => {
    expect(
      countProblemHeads(
        "[서술형 $1$] 둘레의 길이가 $8$인 부채꼴의 넓이를 구하시오.",
      ),
    ).toEqual(["서술형1"]);
  });

  it("머리표가 없는 보통 문항은 빈 목록이다", () => {
    expect(
      countProblemHeads(
        "다음 그림과 같은 평행사변형 ABCD 에서 $∠x$ 의 크기는?",
      ),
    ).toEqual([]);
  });

  /** 같은 번호가 두 번 나오는 것은 **한 문항**이다 — 개수가 아니라 번호로 센다. */
  it("같은 번호가 되풀이돼도 하나로 센다", () => {
    expect(
      countProblemHeads("[서술형 $2$] 앞부분 … [서술형 $2$] 이어지는 부분 …"),
    ).toEqual(["서술형2"]);
  });
});
