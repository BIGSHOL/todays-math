/** 유실이 아니라 **추출기가 남긴 자국**. 뒤에 학원 로고·머리말이 딸려 온다. */
const 오염: Array<[string, string]> = [
  [
    "말미 머리말 오염",
    "두 수의 대소 관계가 옳은 것은? 1. $\\frac{1}{2}>\\frac{1}{3}$ 2. $-4>5$ [그림]",
  ],
];

describe("그림 유실 판정 — 눈으로 확인한 실제 문항", () => {
  it.each(유실)("유실: %s", (_name, content) => {
    expect(classifyFigureNeed(content)).toBe("유실");
  });

  it.each(불필요)("불필요: %s", (_name, content) => {
    expect(classifyFigureNeed(content)).toBe("불필요");
  });

  it.each(오염)("오염: %s", (_name, content) => {
    expect(classifyFigureNeed(content)).toBe("오염");
  });
});

describe("판정 순서 — 오탐 목록이 먼저다", () => {
  /**
   * 「줄기와 잎 그림**이다**」는 `그림이다` 지시어에도 걸린다. 오탐 목록을 먼저 보지 않으면
   * 27건이 통째로 유실로 잡힌다. 순서가 규칙의 일부라는 것을 여기서 고정한다.
   */
  it("약한 지시어는 예외에 진다", () => {
    const weak = "그림그래프에서 별 1개 = 5명입니다. 별 4개는 몇 명입니까?";
    expect(NOT_A_FIGURE.test(weak)).toBe(true);
    expect(classifyFigureNeed(weak)).toBe("불필요");
  });

  it("**강한 지시어는 예외를 이긴다** — 리뷰가 잡은 세 자리", () => {
    for (const c of [
      "다음 상자그림에서 제3사분위수를 구하시오.",
      "다음 그림 4 개 중에서 평행사변형인 것을 모두 고르시오.",
    ]) {
      expect(NOT_A_FIGURE.test(c), c).toBe(true);
      expect(STRONG_DEICTIC.test(c), c).toBe(true);
      expect(classifyFigureNeed(c), c).toBe("유실");
    }
  });

  it("띄어쓰기가 흔들려도 같은 판정이다", () => {
    expect(classifyFigureNeed("다음  그림에서 ∠x 의 크기는?")).toBe("유실");
    expect(classifyFigureNeed("다음\n\n그림과  같은 삼각형")).toBe("유실");
  });
});

describe("그림자는 예외가 아니다 — 낱말로 못 가른다", () => {
  /**
   * 「가로등 그림자」 문항은 수치만으로 풀리는 것도 있지만 그림이 붙어 있는 것이 15건이었다.
   * 예외로 두면 「불필요」라고 단정하게 되므로, 강한 지시어가 없으면 **미분류**로 남긴다 —
   * 미분류는 잠그지 않으니 멀쩡한 문항이 조용히 빠지지 않는다.
   */
  it("지시어가 없으면 미분류", () => {
    expect(
      classifyFigureNeed(
        "키가 $1.6$ m인 윤아가 가로등 밑에서 걸어갈 때 그림자의 끝이 움직이는 속도는?",
      ),
    ).toBe("미분류");
  });

  it("지시어가 있으면 유실", () => {
    expect(
      classifyFigureNeed(
        "다음 그림과 같이 나무의 그림자가 벽에 $1.6m$ 높이까지 걸쳐 있다.",
      ),
    ).toBe("유실");
  });
});

describe("줄기와 잎은 **표가 실제로 있을 때만** 예외다", () => {
  it("표 머리 「줄기 잎」 이 있어야 한다", () => {
    expect(
      hasStemLeafTable("…나타낸 줄기와 잎 그림이다. 줄기 잎 $1$ $0~1~2~5$"),
    ).toBe(true);
    // 선택지에 낱말이 흩어져 있는 것으로는 표라고 볼 수 없다(실측 `019fd1d8-cd51`).
    expect(
      hasStemLeafTable("…줄기와 잎 그림이다. ① 잎이 가장 많은 줄기는?"),
    ).toBe(false);
  });
});

describe("미분류는 «판정 못 함» 이지 «문제 없음» 이 아니다", () => {
  /**
   * 「그림」이 있는데 어느 목록에도 안 걸리면 `미분류` 다. 이 값이 0이 아니면 목록이 아직
   * 눈멀었다는 뜻이고 사람이 표본을 봐야 한다 — 조용히 «불필요» 로 흘리지 않는다.
   */
  it("어느 목록에도 안 걸리면 미분류로 남는다", () => {
    expect(
      classifyFigureNeed("좌표평면 위에 점, 직선, 곡선 등으로 나타낸 그림"),
    ).toBe("미분류");
  });
});
